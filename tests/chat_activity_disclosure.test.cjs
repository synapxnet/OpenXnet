let componentPromise;

/** 编译真实活动组件，避免复制生产逻辑。 / Compile the actual activity component without mirroring production logic. */
async function loadComponent() {
  if (!componentPromise) {
    const filename = path.resolve(__dirname, '../frontend/chat-vite/src/ChatActivity.vue');
    const { descriptor, errors } = parse(fs.readFileSync(filename, 'utf8'), { filename });
    assert.deepEqual(errors, []);
    const vueUrl = pathToFileURL(path.resolve(path.dirname(uiRequire.resolve('vue/package.json')), 'index.mjs')).href;
    const code = compileScript(descriptor, { id: 'chat-activity-disclosure-test', inlineTemplate: true }).content
      .replace(/from ["']vue["']/g, `from '${vueUrl}'`)
      .replace(/import ['"]\.\.\/\.\.\/\.\.\/static\/js\/openxnet-conversation-model\.js['"];?/g, '');
    componentPromise = import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
  }
  return (await componentPromise).default;
}

/** 创建仅记录节点与事件的隔离渲染宿主。 / Create an isolated renderer host that records nodes and events only. */
function createHost() {
  /** 保存真实组件生成的节点。 / Retain nodes generated by the actual component. */
  function node(type, text = '') { return { type, text, props: {}, children: [], parent: null }; }
  const renderer = vue.createRenderer({
    /** 插入或移动节点。 / Insert or move nodes. */
    insert(child, parent, anchor = null) {
      if (child.parent) child.parent.children = child.parent.children.filter((item) => item !== child);
      child.parent = parent;
      const index = anchor ? parent.children.indexOf(anchor) : -1;
      if (index < 0) parent.children.push(child); else parent.children.splice(index, 0, child);
    },
    /** 移除节点。 / Remove nodes. */
    remove(child) { if (child.parent) child.parent.children = child.parent.children.filter((item) => item !== child); },
    /** 建立元素。 / Create elements. */
    createElement: (tag) => node(tag),
    /** 建立文本。 / Create text. */
    createText: (text) => node('#text', text),
    /** 建立注释。 / Create comments. */
    createComment: (text) => node('#comment', text),
    /** 更新文本内容。 / Update text content. */
    setText: (target, text) => { target.text = text; },
    /** 更新元素文本。 / Update element text. */
    setElementText: (target, text) => { target.text = text; target.children = []; },
    /** 获取父节点。 / Get the parent node. */
    parentNode: (target) => target.parent,
    /** 获取相邻节点。 / Get the next sibling. */
    nextSibling: (target) => target.parent?.children[target.parent.children.indexOf(target) + 1] || null,
    /** 保存属性与实际事件处理器。 / Retain attributes and actual event handlers. */
    patchProp: (target, key, previous, next) => { target.props[key] = next; },
  });
  return { renderer, root: node('root') };
}

/** 遍历真实渲染树以定位可操作控件。 / Traverse the actual render tree to find usable controls. */
function nodes(root, predicate) {
  return [...(predicate(root) ? [root] : []), ...root.children.flatMap((child) => nodes(child, predicate))];
}

/** 查找完整类名，避免误匹配相似控件。 / Find complete class names without matching similar controls. */
function byClass(root, className) {
  return nodes(root, (node) => String(node.props.class || '').split(/\s+/).includes(className));
}

/** 读取用户可见文本，忽略注释。 / Read user-visible text while excluding comments. */
function textOf(root) {
  return (root.type === '#comment' ? '' : root.text) + root.children.map(textOf).join('');
}

/** 挂载真实组件并自动清理。 / Mount the actual component and clean it up automatically. */
async function mount(t, steps, options = {}) {
  const { renderer, root } = createHost();
  const component = await loadComponent();
  const inspections = [];
  const state = vue.reactive({ activity: { steps, active: options.active !== false }, isZh: options.isZh !== false });
  const app = renderer.createApp({
    /** 保持可更新 props 以验证消息切换。 / Keep props reactive for message-switch verification. */
    render() { return vue.h(component, { ...state, onInspect: (selection) => inspections.push(selection) }); },
  });
  app.mount(root);
  t.after(() => app.unmount());
  return { root, state, inspections };
}

/** 通过主步骤按钮展开内联记录。 / Expand an inline record through its primary step button. */
async function expand(root, index = 0) {
  byClass(root, 'oxc-worklog__step')[index].props.onClick();
  await vue.nextTick();
}

/** 查找实际展示的输入或回执分段。 / Find an actual displayed input or receipt section. */
function section(root, key) {
  return nodes(root, (node) => node.props['data-section'] === key)[0];
}

/** 使用内存剪贴板替身，禁止修改系统剪贴板。 / Use an in-memory clipboard double without modifying the system clipboard. */
function mockClipboard(t, writeText) {
  const descriptor = Object.getOwnPropertyDescriptor(globalThis, 'navigator');
  Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { clipboard: { writeText } } });
  /** 恢复测试前的全局对象。 / Restore the previous global object after the test. */
  t.after(() => { if (descriptor) Object.defineProperty(globalThis, 'navigator', descriptor); else delete globalThis.navigator; });
}

/** 智能体名称打开协作详情，工具按钮保持内联展开。 / Agent names open collaboration details while tool buttons retain inline expansion. */
test('subagents have distinct glyphs and names open their inspector while tools expand inline', async (t) => {
  const { root, inspections } = await mount(t, [
    { id: 'agent', kind: 'subagent', agentId: 'worker-7', taskId: 'task-3', title: 'Read evidence', status: 'done', output: 'Read-only evidence' },
    { id: 'tool', kind: 'tool', title: 'Inspect input', status: 'pending', input: { record: 'example' } },
  ]);
  assert.equal(byClass(root, 'oxc-worklog__disclosure').length, 0);
  assert.equal(byClass(root, 'oxc-worklog__step')[0].props['aria-expanded'], undefined);
  assert.equal(byClass(root, 'oxc-agent-glyph').length, 1);
  await expand(root);
  assert.equal(byClass(root, 'oxc-worklog__disclosure').length, 0);
  assert.deepEqual(inspections, [{ kind: 'activity', stepId: 'agent' }]);
  assert.match(textOf(root), /子智能体/);
  byClass(root, 'oxc-worklog__inspect')[0].props.onClick();
  assert.equal(inspections.length, 2);
  await expand(root, 1);
  assert.equal(byClass(root, 'oxc-worklog__disclosure').length, 1);
  assert.match(textOf(root), /example/);
  await expand(root, 1);
  assert.equal(byClass(root, 'oxc-worklog__disclosure').length, 0);
});

/** 明确命令字段可以展示，其余参数不可丢失。 / Explicit command fields render while all other arguments remain available. */
test('structured command fields render without discarding input options', async (t) => {
  for (const key of ['cmd', 'command']) {
    const input = { [key]: 'python --version', cwd: 'E:\\review workspace', timeout: 0 };
    const { root } = await mount(t, [{ id: key, title: 'Inspect runtime', status: 'done', input, output: 'Python 3.12' }]);
    await expand(root);
    assert.equal(byClass(section(root, 'command'), 'oxc-worklog__record')[0].text, 'python --version');
    assert.equal(byClass(section(root, 'input'), 'oxc-worklog__record')[0].text, JSON.stringify({ cwd: 'E:\\review workspace', timeout: 0 }, null, 2));
    assert.equal(input[key], 'python --version');
    assert.equal(byClass(section(root, 'output'), 'oxc-worklog__record')[0].text, 'Python 3.12');
  }
  const { root } = await mount(t, [{ id: 'top', command: ['python', '--version'], input: { timeout: 1 }, status: 'done' }]);
  await expand(root);
  assert.equal(byClass(section(root, 'command'), 'oxc-worklog__record')[0].text, '[\n  "python",\n  "--version"\n]');
  assert.match(textOf(section(root, 'input')), /timeout/);
});


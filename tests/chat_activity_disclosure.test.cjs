/** 流式新增内容不能沿用旧内容的复制成功提示。 / Streamed content must not inherit a successful copy notice for earlier text. */
test('updated output retains its disclosure but clears an outdated copy notice', async (t) => {
  const copied = [];
  mockClipboard(t, async (text) => { copied.push(text); });
  const { root, state } = await mount(t, [{ id: 'stream', status: 'running', output: 'First chunk' }]);
  await expand(root);
  await byClass(section(root, 'output'), 'oxc-worklog__copy-action')[0].props.onClick();
  await vue.nextTick();
  assert.match(textOf(section(root, 'output')), /已复制到剪贴板/);
  state.activity.steps[0].output = 'First chunk\nSecond chunk';
  await vue.nextTick();
  assert.equal(byClass(root, 'oxc-worklog__disclosure').length, 1);
  assert.equal(byClass(section(root, 'output'), 'oxc-worklog__record')[0].text, 'First chunk\nSecond chunk');
  assert.doesNotMatch(textOf(section(root, 'output')), /已复制到剪贴板/);
  assert.deepEqual(copied, ['First chunk']);
});

/** 消息切换清理局部展开并丢弃迟到的复制结果。 / Switching messages clears disclosure and discards late clipboard results. */
test('changing activity clears inline state and ignores stale clipboard completion', async (t) => {
  let resolveCopy;
  mockClipboard(t, () => new Promise((resolve) => { resolveCopy = resolve; }));
  const { root, state } = await mount(t, [{ id: 'old', status: 'done', output: 'Old receipt' }]);
  await expand(root);
  const pending = byClass(section(root, 'output'), 'oxc-worklog__copy-action')[0].props.onClick();
  await vue.nextTick();
  assert.equal(byClass(section(root, 'output'), 'oxc-worklog__copy-action')[0].props.disabled, true);
  state.activity = { active: true, steps: [{ id: 'new', status: 'pending', output: 'New receipt' }] };
  await vue.nextTick();
  assert.equal(byClass(root, 'oxc-worklog__disclosure').length, 0);
  resolveCopy();
  await pending;
  await expand(root);
  assert.match(textOf(section(root, 'output')), /New receipt/);
  assert.doesNotMatch(textOf(root), /Old receipt|已复制|复制中/);
});

/** 回复结束收起一次，历史记录可重新展开且后续回执不抢回用户选择。 / Fold once at reply completion and preserve manual reopening across later receipts. */
test('reply completion collapses activity and file details once while preserving reopening', async (t) => {
  const { root, state } = await mount(t, [{ id: 'edit', status: 'running', fileChanges: [{ id: 'f', path: 'src/a.py', operation: 'modify', status: 'running', diff: '-old\n+new', contentSource: 'request' }] }]);
  await expand(root);
  byClass(root, 'oxc-worklog__file-toggle')[0].props.onClick();
  await vue.nextTick();
  assert.equal(byClass(root, 'oxc-worklog__file-detail').length, 1);
  state.activity.active = false;
  await vue.nextTick();
  assert.equal(byClass(root, 'oxc-worklog__body').length, 0);
  assert.match(textOf(root), /1 个文件/);
  byClass(root, 'oxc-worklog__toggle')[0].props.onClick();
  await vue.nextTick();
  assert.equal(byClass(root, 'oxc-worklog__disclosure').length, 0);
  assert.equal(byClass(root, 'oxc-worklog__file-detail').length, 0);
  state.activity.steps[0].status = 'done';
  await vue.nextTick();
  assert.equal(byClass(root, 'oxc-worklog__body').length, 1);
});


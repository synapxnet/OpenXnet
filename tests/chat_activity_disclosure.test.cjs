/** 文件差异保持惰性，长文本限制渲染但复制完整已收数据。 / Keep diffs inert and bound rendering while copying all received text. */
test('file diff rendering is inert bounded and exactly copyable', async (t) => {
  const copied = [];
  mockClipboard(t, async (text) => { copied.push(text); });
  const diff = ['+<script>evil()</script>', ...Array.from({ length: 550 }, (_, i) => `+line ${i}`)].join('\n');
  const { root } = await mount(t, [{ id: 'safe', status: 'done', fileChanges: [{ id: 'f', path: 'src/<img>.txt', operation: 'write', status: 'done', confirmed: true, diff, contentSource: 'receipt' }] }]);
  byClass(root, 'oxc-worklog__file-toggle')[0].props.onClick();
  await vue.nextTick();
  assert.equal(nodes(root, (node) => node.type === 'script' || node.type === 'img' || node.props.innerHTML !== undefined).length, 0);
  const detail = byClass(root, 'oxc-worklog__file-detail')[0];
  assert.equal(nodes(detail, (node) => node.type === 'span' && node.props.class === 'is-added').length, 500);
  assert.match(textOf(detail), /展示前 500 行/);
  await byClass(detail, 'oxc-worklog__copy-action')[0].props.onClick();
  await vue.nextTick();
  assert.deepEqual(copied, [diff]);
  assert.match(textOf(detail), /已复制/);
});
